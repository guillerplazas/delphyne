"""
Experiment for the split-model sketch-guided step-by-step proof strategy.

The sketch is generated by `gpt-5.4`, while the step execution model is
swept over `gpt-5.4-mini` and `gpt-5.4-nano` with reasoning effort as
our primary tuning axis.
"""

import delphyne as dp
import mini_eqns_experiments as meq

SKETCH_MODEL = "gpt-5.4"
STEP_CONFIGS = [
    ("gpt-5.4-nano", "medium", "medium"),
]

configs = [
    meq.StepByStepConfig(
        bench_name=bench_name,
        sketch_model_name=SKETCH_MODEL,
        step_model_name=step_model_name,
        sketch_reasoning_effort=sketch_reasoning_effort,
        step_reasoning_effort=step_reasoning_effort,
        num_completions=1,
        max_feedback_cycles_per_step=4,
        max_steps=30,
        max_sketch_feedback_cycles=2,
        loop=True,
        max_dollar_budget=0.25,
        seed=seed,
    )
    for bench_name in list(meq.BENCHS.keys())
    for (step_model_name, sketch_reasoning_effort, step_reasoning_effort) in STEP_CONFIGS
    for seed in range(1)
]

if __name__ == "__main__":
    dp.Experiment(
        config_class=meq.StepByStepConfig,
        context=dp.workspace_execution_context(__file__),
        configs=configs,
        output_dir=f"experiments/report/{dp.path_stem(__file__)}_9",
    ).run_cli()
