"""
Problem pools the ACE adaptation driver can adapt on.

Deliberately NOT registered in `experiments/common/miniF2F_bench.py`: sixteen
frozen experiment scripts import that module at startup, and
`load_partition` raises on a missing file, so adding a fourth partition
there would make every one of them fail to import the day the pool file
is absent. Adaptation-only state belongs in an adaptation-only module.

`ADAPT_POOL` is generated by `tools/data/make_pool.py` (run
`python -m tools.data.make_pool --check` to prove it still matches its rule).
"""

# pyright: strict

from collections.abc import Mapping

import experiments.common.miniF2F_bench as mf

ADAPT_POOL_FILE = "benchmarks/adapt_pool.txt"

ADAPT_POOL: Mapping[str, tuple[str, str]] = mf.load_partition(ADAPT_POOL_FILE)
"""
The ~100-problem adaptation corpus: never evaluated, drawn from the
miniF2F problems no partition uses (both splits — see the file header).
"""

assert not (set(ADAPT_POOL) & set(mf.ALL_PROBLEMS)), (
    "the adaptation pool must be disjoint from every benchmark "
    "partition — adapting on an evaluated problem makes that "
    "problem in-sample and the evaluation meaningless"
)

POOLS: Mapping[str, Mapping[str, tuple[str, str]]] = {
    "train": mf.TRAIN_PROBLEMS,
    "validation": mf.VALIDATION_PROBLEMS,
    "test": mf.TEST_PROBLEMS,
    "adapt_pool": ADAPT_POOL,
}
"""Every pool the adaptation driver's `--variant` may name."""

ALL_ADAPT_PROBLEMS: Mapping[str, tuple[str, str]] = {
    **mf.ALL_PROBLEMS,
    **ADAPT_POOL,
}
"""
Every problem an adaptation config may reference, keyed by theorem
name. `miniF2F_bench.ALL_PROBLEMS` covers only the partitions, so the
pool has to be unioned in for `instantiate` to resolve a pool problem.
"""
