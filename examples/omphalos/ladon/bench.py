"""
The Ladon selection partition and the configuration class of its arms.

`ladonX` (`ladon/ladonX.txt`, generated by `ladon/make_partition.py`)
is where every Ladon arm is paired against the canonical baseline
(`experiments/x_ladon_experiment.py`, two seeds, 80 cells). It exists
because validationX has been read for selection by every arm since
2026-08-25 (HINTS #67) and an autonomous loop must not add to that.

`LadonConfig` is `minif2f_x.XAgenticConfig` with one difference: it
resolves bench names against ladonX first, then the X partitions (the
smoke cells are trainX problems). A subclass rather than a registration
in `minif2f_x.py`, so the frozen X module and its asserts stay
untouched; the identity space is fresh anyway since every Ladon arm
runs in its own output directory.
"""

# pyright: strict

import sys
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path

_OMPHALOS_DIR = Path(__file__).resolve().parent.parent
for _sub in ("", "experiments"):
    _p = str(_OMPHALOS_DIR / _sub)
    if _p not in sys.path:
        sys.path.insert(0, _p)

import ace_pool  # noqa: E402
import miniF2F_bench as mf  # noqa: E402
import minif2f_x as x  # noqa: E402

LADONX_FILE = "ladon/ladonX.txt"

LADONX_PROBLEMS: Mapping[str, tuple[str, str]] = mf.load_partition(LADONX_FILE)
"""Selection partition of the Ladon loop (two seeds, 80 cells)."""

_ladon = set(LADONX_PROBLEMS)
assert len(_ladon) == 40, len(_ladon)
assert not (_ladon & set(x.ALL_X_PROBLEMS)), (
    "ladonX must be disjoint from trainX/validationX/testX"
)
assert not (_ladon & set(mf.ALL_PROBLEMS)), (
    "ladonX must be disjoint from train/validation/test"
)
assert not (_ladon & set(ace_pool.ADAPT_POOL)), (
    "ladonX must be disjoint from the ACE adaptation pool"
)
assert not any(
    d in _ladon
    for d in mf._DEMO_PROBLEMS  # pyright: ignore[reportPrivateUsage]
), "demonstration problems must not appear in ladonX"

SMOKE_PROBLEMS: tuple[str, ...] = (
    "mathd_numbertheory_35",
    "mathd_algebra_37",
    "mathd_numbertheory_403",
)
"""
The smoke cells of an arm: the three cheapest trainX problems the
archived baseline (`x_train_agentic`) solved on both seeds — under
$0.001 per cell. An implement session runs its arm on these before
Ladon pays for ladonX, so a crash or a broken proof contract surfaces
for cents.
"""
assert all(p in x.TRAINX_PROBLEMS for p in SMOKE_PROBLEMS)

BASELINE_DIR = "experiments/output/x_ladon_agentic"
"""Output directory of the frozen control arm (`x_ladon_experiment.py`)."""


@dataclass
class LadonConfig(x.XAgenticConfig):
    """`XAgenticConfig` whose bench names may come from ladonX."""

    def _problem(self) -> tuple[str, str]:
        if self.bench_name in LADONX_PROBLEMS:
            return LADONX_PROBLEMS[self.bench_name]
        return x.ALL_X_PROBLEMS[self.bench_name]


def ladon_config(
    name: str,
    seed: int,
    *,
    max_dollar_budget: float = x.X_DOLLAR_CAP,
    toolset: str = x.X_TOOLSET,
    reasoning_effort: str = x.X_EFFORT,
) -> LadonConfig:
    """One canonical luna cell on a ladonX (or smoke) problem."""
    return LadonConfig(
        bench_name=name,
        model_name=x.X_MODEL,
        temperature=None,
        toolset=toolset,
        num_requests=x.X_NUM_REQUESTS,
        loop=False,
        seed=seed,
        max_dollar_budget=max_dollar_budget,
        reasoning_effort=reasoning_effort,
    )


config_name = x.x_config_name
"""`{bench}__{toolset}-{effort}__{model}__seed{n}`, read by cell_records."""
